static uint8_t normalizedScale(uint8_t scale)
{
    return (scale == 0U) ? 1U : scale;
}

static void drawScaledPixel(uint16_t x, uint16_t y, uint8_t scale,
    uint16_t color)
{
    LCD8080_fillRect(x, y, scale, scale, color);
}

void LCDText_drawAsciiChar(uint16_t x, uint16_t y, char character,
    uint16_t foreground, uint16_t background,
    uint8_t scale, uint8_t transparent)
{
    uint8_t column;
    uint8_t row;
    uint8_t index;

    scale = normalizedScale(scale);
    if (((uint8_t) character < 0x20U) || ((uint8_t) character > 0x7FU)) {
        character = '?';
    }
    index = (uint8_t) character - 0x20U;

    for (column = 0U; column < 6U; column++) {
        uint8_t bits = (column < 5U) ? gAscii5x7[index][column] : 0U;
        for (row = 0U; row < 8U; row++) {
            uint8_t set = (uint8_t) ((bits >> row) & 1U);
            if ((set != 0U) || (transparent == 0U)) {
                drawScaledPixel((uint16_t) (x + column * scale),
                    (uint16_t) (y + row * scale), scale,
                    (set != 0U) ? foreground : background);
            }
        }
    }
}

void LCDText_drawAsciiString(uint16_t x, uint16_t y, const char *text,
    uint16_t foreground, uint16_t background,
    uint8_t scale, uint8_t transparent)
{
    uint16_t cursorX = x;
    uint16_t cursorY = y;

    if (text == 0) {
        return;
    }
    scale = normalizedScale(scale);

    while (*text != '\0') {
        if (*text == '\n') {
            cursorX = x;
            cursorY = (uint16_t) (cursorY + 8U * scale);
        } else {
            LCDText_drawAsciiChar(cursorX, cursorY, *text,
                foreground, background, scale, transparent);
            cursorX = (uint16_t) (cursorX + 6U * scale);
        }
        text++;
    }
}

void LCDText_drawSoftGlyph(uint16_t x, uint16_t y,
    const LCDText_SoftGlyph *glyph, uint16_t foreground,
    uint16_t background, uint8_t scale, uint8_t transparent)
{
    uint8_t row;
    uint8_t column;
    uint8_t bytesPerRow;

    if ((glyph == 0) || (glyph->bitmap == 0) ||
        (glyph->width == 0U) || (glyph->height == 0U)) {
        return;
    }

    scale = normalizedScale(scale);
    bytesPerRow = (uint8_t) ((glyph->width + 7U) / 8U);
    for (row = 0U; row < glyph->height; row++) {
        for (column = 0U; column < glyph->width; column++) {
            uint8_t bits = glyph->bitmap[(uint16_t) row * bytesPerRow +
                (column / 8U)];
            uint8_t set = (uint8_t) ((bits >> (7U - (column & 7U))) & 1U);
            if ((set != 0U) || (transparent == 0U)) {
                drawScaledPixel((uint16_t) (x + column * scale),
                    (uint16_t) (y + row * scale), scale,
                    (set != 0U) ? foreground : background);
            }
        }
    }
}

static const LCDText_SoftGlyph *findGlyph(
    uint32_t codepoint, const LCDText_SoftGlyph *glyphs, uint32_t glyphCount)
{
    uint32_t index;

    if (glyphs == 0) {
        return 0;
    }
    for (index = 0U; index < glyphCount; index++) {
        if (glyphs[index].codepoint == codepoint) {
            return &glyphs[index];
        }
    }
    return 0;
}

static uint32_t decodeUtf8(const char **text)
{
    const uint8_t *bytes = (const uint8_t *) *text;
    uint32_t codepoint;

    if (bytes[0] < 0x80U) {
        (*text)++;
        return bytes[0];
    }
    if (((bytes[0] & 0xE0U) == 0xC0U) &&
        ((bytes[1] & 0xC0U) == 0x80U)) {
        codepoint = ((uint32_t) (bytes[0] & 0x1FU) << 6) |
            (bytes[1] & 0x3FU);
        *text += 2;
        return codepoint;
    }
    if (((bytes[0] & 0xF0U) == 0xE0U) &&
        ((bytes[1] & 0xC0U) == 0x80U) &&
        ((bytes[2] & 0xC0U) == 0x80U)) {
        codepoint = ((uint32_t) (bytes[0] & 0x0FU) << 12) |
            ((uint32_t) (bytes[1] & 0x3FU) << 6) |
            (bytes[2] & 0x3FU);
        *text += 3;
        return codepoint;
    }

    (*text)++;
    return (uint32_t) '?';
}

static void drawMissingGlyph(uint16_t x, uint16_t y, uint8_t scale,
    uint16_t foreground, uint16_t background, uint8_t transparent)
{
    uint16_t size = (uint16_t) (16U * scale);

    if (transparent == 0U) {
        LCD8080_fillRect(x, y, size, size, background);
    }
    LCD8080_fillRect(x, y, size, scale, foreground);
    LCD8080_fillRect(x, (uint16_t) (y + size - scale), size, scale, foreground);
    LCD8080_fillRect(x, y, scale, size, foreground);
    LCD8080_fillRect((uint16_t) (x + size - scale), y, scale, size, foreground);
}

void LCDText_drawUtf8(uint16_t x, uint16_t y, const char *utf8,
    const LCDText_SoftGlyph *glyphs, uint32_t glyphCount,
    uint16_t foreground, uint16_t background,
    uint8_t scale, uint8_t transparent)
{
    uint16_t cursorX = x;
    uint16_t cursorY = y;

    if (utf8 == 0) {
        return;
    }
    scale = normalizedScale(scale);

    while (*utf8 != '\0') {
        uint32_t codepoint = decodeUtf8(&utf8);

        if (codepoint == (uint32_t) '\n') {
            cursorX = x;
            cursorY = (uint16_t) (cursorY + 16U * scale);
        } else if (codepoint < 0x80U) {
            LCDText_drawAsciiChar(cursorX, cursorY, (char) codepoint,
                foreground, background, scale, transparent);
            cursorX = (uint16_t) (cursorX + 6U * scale);
        } else {
            const LCDText_SoftGlyph *glyph =
                findGlyph(codepoint, glyphs, glyphCount);
            if (glyph != 0) {
                LCDText_drawSoftGlyph(cursorX, cursorY, glyph,
                    foreground, background, scale, transparent);
                cursorX = (uint16_t) (cursorX + glyph->width * scale);
            } else {
                drawMissingGlyph(cursorX, cursorY, scale,
                    foreground, background, transparent);
                cursorX = (uint16_t) (cursorX + 16U * scale);
            }
        }
    }
}
